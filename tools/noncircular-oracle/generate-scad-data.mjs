import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { FITS, axialDesign } from "./oracle.mjs";
import { generateMechanism } from "./geometry.mjs";

const configs = [
  { lobes: 4, e1: 0.04125, radius: (45 - 5) / (3 * (1 + 0.04125)) },
  { lobes: 3, e1: 0.04950, radius: (45 - 5) / (3 * (1 + 0.04950)) },
];

function perpendicularDistance(p, a, b) {
  const dx=b[0]-a[0],dy=b[1]-a[1],d2=dx*dx+dy*dy;
  const t=d2?Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/d2)):0;
  return Math.hypot(p[0]-a[0]-t*dx,p[1]-a[1]-t*dy);
}
function simplifyOpen(points, epsilon) {
  if(points.length<3)return points;
  let best=0,index=0;
  for(let i=1;i<points.length-1;i++){const d=perpendicularDistance(points[i],points[0],points.at(-1));if(d>best){best=d;index=i;}}
  if(best<=epsilon)return [points[0],points.at(-1)];
  return simplifyOpen(points.slice(0,index+1),epsilon).slice(0,-1).concat(simplifyOpen(points.slice(index),epsilon));
}
function simplifyRing(r, epsilon=.012) {
  const pts=r.slice(0,-1); let split=1;
  for(let i=2;i<pts.length;i++)if(Math.hypot(pts[i][0]-pts[0][0],pts[i][1]-pts[0][1])>Math.hypot(pts[split][0]-pts[0][0],pts[split][1]-pts[0][1]))split=i;
  const out=simplifyOpen(pts.slice(0,split+1),epsilon).slice(0,-1).concat(simplifyOpen(pts.slice(split).concat([pts[0]]),epsilon).slice(0,-1));
  return out;
}
function scadPolygon(mp) {
  const area=r=>Math.abs(r.reduce((s,p,i)=>{const q=r[(i+1)%r.length];return s+p[0]*q[1]-q[0]*p[1]},0)/2);
  const rings=mp[0].map(r=>r.slice(0,-1)).filter(r=>r.length>=3&&area(r)>1e-4); const points=rings.flat(); let at=0;
  const paths=rings.map(r=>{const p=Array.from({length:r.length},(_,i)=>at+i);at+=r.length;return p;});
  return `[${JSON.stringify(points)},${JSON.stringify(paths)}]`;
}
function rayRadius(ring,angle){const d=[Math.cos(angle),Math.sin(angle)];let far=0;for(let i=0;i<ring.length-1;i++){const a=ring[i],b=ring[i+1],ex=b[0]-a[0],ey=b[1]-a[1],den=d[0]*ey-d[1]*ex;if(Math.abs(den)<1e-10)continue;const t=(a[0]*ey-a[1]*ex)/den,u=(a[0]*d[1]-a[1]*d[0])/den;if(t>=0&&u>=0&&u<=1)far=Math.max(far,t);}return far;}
function radialRing(source,count=3600){const out=Array.from({length:count},(_,i)=>{const a=2*Math.PI*i/count,r=rayRadius(source,a);return[r*Math.cos(a),r*Math.sin(a)]});return out.concat([out[0]]);}
function cleanProfile(mp,kind){return kind===2?[[radialRing(mp[0][0]),radialRing(mp[0][1])]]:[[radialRing(mp[0][0])]];}
function smoothRadii(r,teeth,count=720){const raw=Array.from({length:count},(_,i)=>rayRadius(r,2*Math.PI*i/count));const half=Math.max(2,Math.round(count/teeth/2));return raw.map((_,i)=>{let s=0;for(let j=-half;j<=half;j++)s+=raw[(i+j+count)%count];return s/(2*half+1);});}
function channelProfiles(mech,recess=.5){const count=720,d=1.25*mech.planet.module+recess;
  const body=profile=>{const rr=smoothRadii(profile[0][0],mech.planet.teeth,count);return [[Array.from({length:count+1},(_,i)=>{const a=2*Math.PI*(i%count)/count,r=rr[i%count]-d;return [r*Math.cos(a),r*Math.sin(a)];})]];};
  const hole=mech.ring[0][1],rr=smoothRadii(hole,3*mech.planet.teeth,count),outer=mech.ring[0][0];
  const cavity=Array.from({length:count+1},(_,i)=>{const a=2*Math.PI*(i%count)/count,r=rr[i%count]+d;return [r*Math.cos(a),r*Math.sin(a)];});
  return [body(mech.planet.polygon),body(mech.sun),[[outer,cavity]]];
}

const data=[];
for(let shape=0;shape<configs.length;shape++){
  const c=configs[shape]; const byFit=[];
  for(const fit of FITS){
    const base=generateMechanism({...c,module:1,pressureAngle:25,posesPerPitch:8,phaseArc:0,backlash:fit.backlash,outerRadius:45});
    const axial=axialDesign(base.planet.module,fit,8.4); const phases=[];
    for(const [i,phaseArc] of [0,axial.delta,2*axial.delta].entries()){
      const mech=i===0?base:generateMechanism({...c,module:1,pressureAngle:25,posesPerPitch:8,phaseArc,backlash:fit.backlash,outerRadius:45});
      const channels=channelProfiles(mech);
      phases.push(`[${scadPolygon(cleanProfile(mech.planet.polygon,0))},${scadPolygon(cleanProfile(mech.sun,1))},${scadPolygon(cleanProfile(mech.ring,2))},${channels.map(scadPolygon).join(",")}]`);
    }
    byFit.push(`[${phases.join(",")}]`);
  }
  data.push(`[${byFit.join(",")}]`);
}
const text=`// Generated by tools/noncircular-oracle/generate-scad-data.mjs; do not edit.\nncg_profiles=[${data.join(",")}];\n`;
writeFileSync(resolve(import.meta.dirname,"../../examples/scad/planetary-fidget-noncircular/lib/ncg_profiles.scad"),text);
console.log(`wrote ${text.length} bytes`);
